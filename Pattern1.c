#include<stdio.h>
    int main()
        {
            int a=5;//number of rows
            int i;
            int j;
            
            for(i=0;i<=a;i++)
            {
                for(j=0;j<=i;j++)
                {
                printf(" * ");
                }
                printf("\n");
            }
            
            return 0;

        }
    